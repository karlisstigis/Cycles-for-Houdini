"""Check that the paths, scripts and options named in the entry documents exist.

The documents listed in DOCUMENTS tell newcomers which files to open and which commands to run.
This check reads every inline code span, every line of a fenced code block (Mermaid diagrams excepted) and every
relative Markdown link in them, and reports:

- a repository path that is not a tracked file or a folder that holds tracked files;
- a bare file name that no tracked file has (also a whole span naming a .cmd file with spaces in its name);
- a link target or #anchor that does not exist;
- an option given to one of our scripts (``./scripts/x.ps1 -Name``, ``python scripts/x.py --name``) that the
  script does not define.

Placeholders are skipped: anything containing < > $ % * or ..., and the marker [PENDING-NAME: ...]. Paths that are
generated by the build, private, or not merged yet are listed below with a reason. A PENDING entry that exists
fails too, so the list cannot go stale.

With --all-links it also checks every relative link (and #anchor) in every tracked Markdown file, so that no
document points to a file that is not in the repository. It reads the Git index in a checkout and the files on
disk in an unpacked source ZIP. Exit code 1 when anything is missing.
"""

import argparse
import os
import re
import runpy
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

DOCUMENTS = (
    "README.md",
    "CONTRIBUTING.md",
    "docs/user/build-it-yourself.md",
    "docs/dev/README.md",
    "docs/dev/architecture-overview.md",
)

# Created by the build or by bootstrap; never tracked.
GENERATED = {
    "third_party/": "downloaded and patched by scripts/bootstrap.ps1 (ignored by git)",
    "bin/ch_worker.exe": "worker executable inside a built Houdini package",
}
# Named on purpose but absent from the public tree.
OPTIONAL = {}
# Not merged at this revision. Remove the entry when the path arrives (the check fails until then).
PENDING = {}
# Paths in other projects, named as examples.
EXTERNAL = {"intern/cycles", "source/blender"}

OUR_ROOTS = ("cmake/", "docs/", "examples/", "houdini/", "include/", "launchers/", "packaging/", "patches/")
OUR_ROOTS += ("scripts/", "src/", "tests/", ".githooks/")
EXTENSIONS = {"md", "json", "py", "ps1", "cmd", "cpp", "h", "txt", "iss", "patch", "toml", "ini", "osl", "hda"}
SKIP = re.compile(r"[<>$%*]|\.\.\.|^https?:|^[A-Za-z]:[\\/]|^\.\.")
PLACEHOLDER = re.compile(r"\[PENDING-NAME:[^\]]*\]")
SCRIPT = re.compile(r"^(?:\./)?(scripts/[\w.-]+\.(?:ps1|py))$")


def published(root, files):
    """The tracked files a published copy of the repository holds.

    A maintainer's checkout also holds files that are not published, and the tool that decides which files are
    (scripts/export-public-source.py, itself not published). If that tool exists, only the files it publishes count,
    so a published document that names or links to an unpublished file is reported here as well.
    """
    tool = root / "scripts/export-public-source.py"
    if not tool.is_file():
        return files
    export = runpy.run_path(str(tool))
    classes = export["classify"](sorted(files), export["load_rules"](tool.with_name("public-export-rules.json")))
    return {path for path, (kind, _) in classes.items() if kind == "public"}


def source_files(root):
    if (root / ".git").exists():
        names = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], check=True, capture_output=True).stdout
        return set(filter(None, names.decode("utf-8").split("\0")))

    generated_roots = {"_work", "third_party", "artifacts", "Installers"}
    generated_directories = {".git", "__pycache__", ".pytest_cache", ".ruff_cache"}
    files = set()
    for directory, children, names in os.walk(root, followlinks=False):
        parent = Path(directory)
        # Exclude Windows junctions too. A source ZIP has ordinary directories.
        children[:] = [
            name
            for name in children
            if name not in generated_directories
            and (parent != root or name not in generated_roots)
            and (parent / name).resolve() == parent / name
        ]
        files.update((parent / name).relative_to(root).as_posix() for name in names if not (parent / name).is_symlink())
    return files


def tracked(root):
    files = published(root, source_files(root))
    folders = {name[: index + 1] for name in files for index, char in enumerate(name) if char == "/"}
    return files, folders


def slug(heading):
    text = re.sub(r"[`*_]", "", heading.strip().lower())
    return re.sub(r"\s", "-", re.sub(r"[^\w\s-]", "", text))


def anchors(path):
    """Heading anchors as GitHub makes them; a repeated heading gets -1, -2, ... appended."""
    found = set()
    fenced = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and re.match(r"#{1,6}\s", line):
            name = slug(line.lstrip("#"))
            candidate, number = name, 0
            while candidate in found:
                number += 1
                candidate = f"{name}-{number}"
            found.add(candidate)
    return found


def spans(text):
    """Yield (kind, text) for code lines, inline code spans and link targets."""
    text = PLACEHOLDER.sub("", text)
    fence = None
    prose = []
    for line in text.splitlines():
        if line.startswith("```"):
            fence = None if fence is not None else line[3:].strip()
            continue
        if fence is not None:
            if fence != "mermaid":
                yield "code", line.split(" #")[0]
            continue
        prose.append(line)
    prose = "\n".join(prose)
    for match in re.finditer(r"`([^`\n]+)`", prose):
        yield "code", match.group(1)
    for match in re.finditer(r"\]\(([^)\s]+)\)", re.sub(r"`[^`\n]+`", "", prose)):
        yield "link", match.group(1)


def clean(token):
    token = token.strip("\"'(),;").rstrip(".:")
    return re.sub(r":\d+$", "", token)


class Checker:
    def __init__(self, root):
        self.root = root
        self.files, self.folders = tracked(root)
        self.basenames = {name.rsplit("/", 1)[-1] for name in self.files}
        self.problems = []

    def exists(self, path):
        return path in self.files or path.rstrip("/") + "/" in self.folders

    def known_exception(self, path):
        for table in (GENERATED, OPTIONAL, PENDING):
            for name in table:
                if path == name or path.rstrip("/") == name.rstrip("/") or path.startswith(name):
                    return True
        return any(path == name or path.startswith(name + "/") for name in EXTERNAL)

    def path(self, document, token):
        if self.known_exception(token) or self.exists(token):
            return
        if "/" not in token.rstrip("/"):
            if token not in self.basenames:
                self.problems.append(f"{document}: no tracked file is named {token}")
            return
        if token.startswith(OUR_ROOTS):
            self.problems.append(f"{document}: {token} does not exist")
        elif not any(name.endswith("/" + token.rstrip("/")) or ("/" + token) in name for name in self.files):
            self.problems.append(f"{document}: no tracked path ends with {token}")

    def options(self, document, script, tokens):
        text = (self.root / script).read_text(encoding="utf-8", errors="replace")
        for position, token in enumerate(tokens):
            if "/" in token or SKIP.search(token):
                break  # the next path starts another program's arguments
            name = token.split(":")[0].split("=")[0]
            if script.endswith(".ps1") and name.startswith("-") and len(name) > 1:
                if not re.search(r"\$" + re.escape(name[1:]) + r"\b", text, re.IGNORECASE):
                    self.problems.append(f"{document}: {script} has no parameter {name}")
            elif script.endswith(".py") and name.startswith("--"):
                if name not in text:
                    self.problems.append(f"{document}: {script} has no option {name}")
            elif script.endswith(".py") and position == 0 and re.fullmatch(r"[a-z][a-z-]*", name):
                if f'"{name}"' not in text and f"'{name}'" not in text:
                    self.problems.append(f"{document}: {script} has no command {name}")

    def code(self, document, text):
        whole = clean(text.strip())
        if " " in whole and (whole in self.files or whole.endswith(".cmd")):
            # A double-click file whose name has spaces, such as "START HERE - Build Cycles for Houdini.cmd"
            # or "launchers/Build and make installer.cmd".
            self.path(document, whole)
            return
        tokens = [clean(token) for token in text.split()]
        for index, token in enumerate(tokens):
            if not token or SKIP.search(token) or token.startswith("-"):
                continue
            script = SCRIPT.match(token)
            if script:
                self.path(document, script.group(1))
                if (self.root / script.group(1)).is_file():
                    self.options(document, script.group(1), tokens[index + 1 :])
                continue
            if "\\" in token or "=" in token or token.startswith("."):
                continue
            extension = token.rsplit(".", 1)[-1] if "." in token.rsplit("/", 1)[-1] else ""
            if "/" in token or extension in EXTENSIONS:
                self.path(document, token)

    def link(self, document, target):
        if re.match(r"^[a-z]+:", target):
            return
        location, _, anchor = target.partition("#")
        base = (self.root / document).parent
        resolved = (base / location).resolve() if location else (self.root / document).resolve()
        try:
            relative = resolved.relative_to(self.root.resolve()).as_posix()
        except ValueError:
            self.problems.append(f"{document}: link {target} leaves the repository")
            return
        if location and not (self.known_exception(relative) or self.exists(relative)):
            self.problems.append(f"{document}: link {target} points to a missing file")
        elif anchor and resolved.suffix == ".md" and resolved.is_file() and anchor not in anchors(resolved):
            self.problems.append(f"{document}: link {target} names a missing heading")

    def run(self):
        for name in PENDING:
            if self.exists(name):
                self.problems.append(f"{name} now exists: remove it from PENDING in scripts/check-doc-paths.py")
        for document in DOCUMENTS:
            path = self.root / document
            if not path.is_file():
                self.problems.append(f"{document} is missing")
                continue
            for kind, text in spans(path.read_text(encoding="utf-8")):
                (self.code if kind == "code" else self.link)(document, text)
        return self.problems

    def run_all_links(self):
        """Check the relative links of every Markdown file (the entry documents' other checks are in run())."""
        documents = sorted(name for name in self.files if name.endswith(".md"))
        for document in documents:
            for kind, text in spans((self.root / document).read_text(encoding="utf-8")):
                if kind == "link":
                    self.link(document, text)
        return documents


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT, help="repository to check (default: this one)")
    parser.add_argument("--all-links", action="store_true", help="also check the links of every Markdown file")
    args = parser.parse_args(argv)
    checker = Checker(args.root.resolve())
    problems = checker.run()
    count = len(DOCUMENTS)
    if args.all_links:
        count = len(checker.run_all_links())
        problems = list(dict.fromkeys(checker.problems))
    for problem in problems:
        print(problem)
    print(f"{len(problems)} problem(s) in {count} documents")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
