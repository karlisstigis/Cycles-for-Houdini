"""Explicit, scene-scoped texture derivative actions.

Original image paths are never deletion targets. Only renderer-created derivatives
with matching provenance and unchanged contents can be removed. Older unmarked
caches remain available to rendering and are reported as unowned by Clear.
"""

from __future__ import annotations

from contextlib import nullcontext
import hashlib
import os
from pathlib import Path
import re
import stat

_REVISION = re.compile(r"[0-9a-fA-F]{32}")
_HEX = re.compile(r"[0-9a-fA-F]{32}")
_PRODUCER = "cycles_houdini.generated_texture/1"
_MAX_ENTRIES = 100_000


def _plain_path(path):
    """Reject symlinks, Windows junctions/reparse points and linked files."""
    path = Path(os.path.abspath(path))
    for part in (path, *path.parents):
        try:
            info = part.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & 0x400:
            raise ValueError("Linked texture cache paths are not eligible: " + str(part))
        if stat.S_ISREG(info.st_mode) and info.st_nlink != 1:
            raise ValueError("Hardlinked texture cache files are not eligible: " + str(part))
    return path


def _destination(source, destination):
    source = _plain_path(source)
    destination = _plain_path(destination)
    if (
        destination == source
        or destination.parent.parent != source.parent / "cycles_houdini"
        or not _REVISION.fullmatch(destination.parent.name)
    ):
        raise ValueError("Cache destination is outside the source's generated namespace")
    suffix = destination.name.removeprefix(source.name)
    if suffix == destination.name or not re.fullmatch(r"(?:\.[0-9]+-|\.portable-)[0-9a-fA-F]{32}\.tx", suffix):
        raise ValueError("Unexpected generated texture cache filename")
    return destination


def _digest(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "md5").hexdigest()


def _owned(source, destination):
    """Require a small versioned marker and the original generated bytes."""
    destination = _destination(source, destination)
    marker = _plain_path(str(destination) + ".ch-cache")
    if not marker.is_file() or marker.stat().st_size > 256:
        return False
    fields = marker.read_text(encoding="ascii").splitlines()
    if len(fields) != 4 or fields[0] != _PRODUCER or not _HEX.fullmatch(fields[2]):
        return False
    source_id = hashlib.md5(str(source).replace("\\", "/").encode("utf-8")).hexdigest()
    if fields[1].lower() != source_id or not fields[3].isdigit():
        return False
    return (
        destination.is_file()
        and destination.stat().st_size == int(fields[3])
        and _digest(destination) == fields[2].lower()
    )


def generate(items, generate_native, progress=None):
    """Generate exactly the native plans supplied; no renderer or output image."""
    report = dict(action="generate", generated=[], reused=[], skipped=[], errors=[])
    for index, item in enumerate(items):
        if progress:
            progress(index / max(len(items), 1), item["source"])
        source, target = item["source"], item["destination"]
        try:
            if not target or source.startswith("op:"):
                report["skipped"].append(source)
                continue
            destination = _destination(source, target)
            # Never overwrite an unowned image, even in a cache-shaped folder.
            existed = destination.exists()
            if existed and not _owned(source, destination):
                report["skipped"].append(str(destination))
                continue
            generate_native(item["handle"])
            report["reused" if existed else "generated"].append(str(destination))
        except (OSError, ValueError, RuntimeError, UnicodeError) as error:
            report["errors"].append(dict(source=source, message=str(error)))
    if progress:
        progress(1.0, "Complete")
    return report


def clear(items, progress=None):
    """Unlink positively identified derivatives for the scene's file sources."""
    report = dict(action="clear", cleared=[], skipped=[], errors=[])
    sources = sorted({item["source"] for item in items if not item["source"].startswith("op:")})
    original_paths = {os.path.normcase(os.path.abspath(source)) for source in sources}
    inspected = 0
    for index, source_text in enumerate(sources):
        if progress:
            progress(index / max(len(sources), 1), source_text)
        try:
            source = _plain_path(source_text)
            root = _plain_path(source.parent / "cycles_houdini")
            if not root.is_dir():
                continue
            for revision in root.iterdir():
                inspected += 1
                if inspected > _MAX_ENTRIES:
                    raise RuntimeError("Texture cache scan exceeded its bounded entry limit")
                if not _REVISION.fullmatch(revision.name):
                    continue
                _plain_path(revision)
                if not revision.is_dir():
                    continue
                for candidate in revision.iterdir():
                    inspected += 1
                    if inspected > _MAX_ENTRIES:
                        raise RuntimeError("Texture cache scan exceeded its bounded entry limit")
                    if not candidate.name.startswith(source.name + ".") or candidate.suffix != ".tx":
                        continue
                    if progress:
                        progress(index / max(len(sources), 1), str(candidate))
                    if os.path.normcase(os.path.abspath(candidate)) in original_paths:
                        report["skipped"].append(str(candidate))
                        continue
                    try:
                        if not _owned(source_text, candidate):
                            report["skipped"].append(str(candidate))
                            continue
                        # Recheck path identity immediately before each unlink.
                        _destination(source, candidate)
                        marker = _plain_path(str(candidate) + ".ch-cache")
                        candidate.unlink()
                        marker.unlink()
                        report["cleared"].append(str(candidate))
                    except (OSError, ValueError, UnicodeError) as error:
                        report["errors"].append(dict(source=str(candidate), message=str(error)))
        except (OSError, ValueError, RuntimeError) as error:
            report["errors"].append(dict(source=source_text, message=str(error)))
    if progress:
        progress(1.0, "Complete")
    return report


def plan_from_rop(rop):
    """Use standard scene extraction, including resolved linked Blender shaders."""
    import hou
    from . import load
    from .scene import native_scene
    from .blender.prototype_leases import PrototypeLeases, split_update

    class Owner:
        pass

    native = load()
    owner = Owner()
    leases = PrototypeLeases(owner)
    handle = native.create("CPU", 1, 1, 1, False, False, False, False, None, True, 1)
    try:
        payload, metadata = split_update(native_scene.capture(rop))
        submission = object()
        leases.begin(submission, metadata)
        snapshot = native.apply(handle, payload, hou.time(), False)
        leases.commit(submission)
        return native.texture_cache_plan(snapshot)
    finally:
        try:
            native.close(handle)
        finally:
            leases.close()


def _from_rop(kwargs, action):
    import hou
    from . import load

    rop = kwargs["node"] if isinstance(kwargs, dict) else kwargs
    ui = hou.isUIAvailable()
    context = (
        hou.InterruptableOperation("Texture Cache " + action.title(), open_interrupt_dialog=True)
        if ui
        else nullcontext()
    )
    with context as operation:

        def progress(fraction, message):
            if operation is not None:
                operation.updateProgress(fraction, message)

        try:
            progress(0, "Collecting scene texture sources")
            items = plan_from_rop(rop)
            report = (
                generate(items, load().texture_cache_generate, progress)
                if action == "generate"
                else clear(items, progress)
            )
        except hou.OperationInterrupted:
            raise
        except Exception as error:
            # Scene acquisition is all-or-nothing. In particular an invalid
            # world source must not turn a partial texture list into deletion.
            report = dict(
                action=action,
                generated=[],
                cleared=[],
                skipped=[],
                errors=[dict(source=rop.path(), message=str(error))],
            )
    rop.setCachedUserData("cycles_houdini.texture_cache", report)
    count = len(report["generated"] if action == "generate" else report["cleared"])
    verb = "generated" if action == "generate" else "cleared"
    message = (
        f"Texture cache: {count} {verb}; {len(report['skipped'])} unowned or ineligible; "
        f"{len(report['errors'])} errors."
    )
    if ui:
        hou.ui.displayMessage(message, details="\n".join(str(error) for error in report["errors"]))
    else:
        print(message)
        for error in report["errors"]:
            print(error["source"] + ": " + error["message"])
    return report


def generate_from_rop(kwargs):
    return _from_rop(kwargs, "generate")


def clear_from_rop(kwargs):
    return _from_rop(kwargs, "clear")
